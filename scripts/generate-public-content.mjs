import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const markerPattern = /<!--\s*public-meta\s*([\s\S]*?)\s*-->/g;
const states = new Set(["active", "authored", "planned"]);

function fail(root, file, message) {
  throw new Error(`[public-content] ${path.relative(root, file)}: ${message}`);
}

async function readMetadata(root, file) {
  const markdown = await readFile(file, "utf8");
  const matches = [...markdown.matchAll(markerPattern)];
  if (matches.length === 0) {
    fail(root, file, 'missing required "<!-- public-meta ... -->" metadata block');
  }
  if (matches.length > 1) {
    fail(root, file, "expected exactly one public-meta metadata block");
  }

  try {
    return JSON.parse(matches[0][1]);
  } catch (error) {
    fail(root, file, `metadata must be valid JSON (${error.message})`);
  }
}

function requireExactKeys(root, file, value, keys) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    fail(root, file, "metadata must be a JSON object");
  }
  const actual = Object.keys(value).sort();
  const expected = [...keys].sort();
  if (actual.length !== expected.length || actual.some((key, index) => key !== expected[index])) {
    fail(root, file, `metadata keys must be exactly: ${expected.join(", ")}`);
  }
}

function requireText(root, file, value, field) {
  if (typeof value !== "string" || value.trim() === "") {
    fail(root, file, `"${field}" must be a non-empty string`);
  }
  return value.trim();
}

function renderPublicContent(stages, souls) {
  return `// Generated by scripts/generate-public-content.mjs. Do not edit.
export type MethodStage = Readonly<{
  n: string;
  title: string;
  body: string;
  tag: string;
}>;

export type PublicSoul = Readonly<{
  name: string;
  mark: string;
  voice: string;
  status: string;
  state: "active" | "authored" | "planned";
}>;

export const stages: readonly MethodStage[] = ${JSON.stringify(stages, null, 2)};

export const souls: readonly PublicSoul[] = ${JSON.stringify(souls, null, 2)};
`;
}

export async function generatePublicContent({ root = projectRoot } = {}) {
  const resolvedRoot = path.resolve(root);
  const outputPath = path.join(resolvedRoot, "src/generated/public-content.ts");
  const methodologyFile = path.join(resolvedRoot, "README.md");
  const methodology = await readMetadata(resolvedRoot, methodologyFile);

  requireExactKeys(resolvedRoot, methodologyFile, methodology, ["methodology"]);
  if (!Array.isArray(methodology.methodology) || methodology.methodology.length === 0) {
    fail(resolvedRoot, methodologyFile, '"methodology" must be a non-empty array');
  }

  const stages = methodology.methodology.map((stage, index) => {
    requireExactKeys(resolvedRoot, methodologyFile, stage, ["body", "tag", "title"]);
    return {
      n: String(index + 1).padStart(2, "0"),
      title: requireText(resolvedRoot, methodologyFile, stage.title, `methodology[${index}].title`),
      body: requireText(resolvedRoot, methodologyFile, stage.body, `methodology[${index}].body`),
      tag: requireText(resolvedRoot, methodologyFile, stage.tag, `methodology[${index}].tag`),
    };
  });

  const soulsDirectory = path.join(resolvedRoot, "souls");
  const soulDirectories = (await readdir(soulsDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("_"))
    .sort((a, b) => a.name.localeCompare(b.name));

  if (soulDirectories.length === 0) {
    fail(resolvedRoot, soulsDirectory, "no public persona directories found");
  }

  const souls = await Promise.all(
    soulDirectories.map(async (directory) => {
      const file = path.join(soulsDirectory, directory.name, "README.md");
      const metadata = await readMetadata(resolvedRoot, file);
      requireExactKeys(resolvedRoot, file, metadata, ["mark", "name", "order", "state", "status", "voice"]);
      if (!Number.isInteger(metadata.order) || metadata.order < 1) {
        fail(resolvedRoot, file, '"order" must be a positive integer');
      }
      if (!states.has(metadata.state)) {
        fail(resolvedRoot, file, `"state" must be one of: ${[...states].join(", ")}`);
      }
      const mark = requireText(resolvedRoot, file, metadata.mark, "mark");
      if (!/^[A-Z]{2,3}$/.test(mark)) {
        fail(resolvedRoot, file, '"mark" must contain 2-3 uppercase letters');
      }
      return {
        order: metadata.order,
        name: requireText(resolvedRoot, file, metadata.name, "name"),
        mark,
        voice: requireText(resolvedRoot, file, metadata.voice, "voice"),
        status: requireText(resolvedRoot, file, metadata.status, "status"),
        state: metadata.state,
      };
    }),
  );

  const orders = souls.map(({ order }) => order);
  if (new Set(orders).size !== orders.length) {
    fail(resolvedRoot, soulsDirectory, 'persona "order" values must be unique');
  }

  souls.sort((a, b) => a.order - b.order);
  const publicSouls = souls.map(({ order: _order, ...soul }) => soul);
  const source = renderPublicContent(stages, publicSouls);

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, "utf8");
  return { outputPath, personaCount: publicSouls.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await generatePublicContent();
    console.log(
      `[public-content] generated ${path.relative(projectRoot, result.outputPath)} from ${result.personaCount + 1} approved Markdown files`,
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
