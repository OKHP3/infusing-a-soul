import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "src/generated/public-content.ts");
const markerPattern = /<!--\s*public-meta\s*([\s\S]*?)\s*-->/;
const states = new Set(["active", "authored", "planned"]);

function fail(file, message) {
  throw new Error(`[public-content] ${path.relative(root, file)}: ${message}`);
}

async function readMetadata(file) {
  const markdown = await readFile(file, "utf8");
  const match = markdown.match(markerPattern);
  if (!match) fail(file, 'missing required "<!-- public-meta ... -->" metadata block');

  try {
    return JSON.parse(match[1]);
  } catch (error) {
    fail(file, `metadata must be valid JSON (${error.message})`);
  }
}

function requireExactKeys(file, value, keys) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    fail(file, "metadata must be a JSON object");
  }
  const actual = Object.keys(value).sort();
  const expected = [...keys].sort();
  if (actual.length !== expected.length || actual.some((key, index) => key !== expected[index])) {
    fail(file, `metadata keys must be exactly: ${expected.join(", ")}`);
  }
}

function requireText(file, value, field) {
  if (typeof value !== "string" || value.trim() === "") {
    fail(file, `"${field}" must be a non-empty string`);
  }
  return value.trim();
}

const methodologyFile = path.join(root, "README.md");
const methodology = await readMetadata(methodologyFile);
requireExactKeys(methodologyFile, methodology, ["methodology"]);
if (!Array.isArray(methodology.methodology) || methodology.methodology.length === 0) {
  fail(methodologyFile, '"methodology" must be a non-empty array');
}

const stages = methodology.methodology.map((stage, index) => {
  requireExactKeys(methodologyFile, stage, ["body", "tag", "title"]);
  return {
    n: String(index + 1).padStart(2, "0"),
    title: requireText(methodologyFile, stage.title, `methodology[${index}].title`),
    body: requireText(methodologyFile, stage.body, `methodology[${index}].body`),
    tag: requireText(methodologyFile, stage.tag, `methodology[${index}].tag`),
  };
});

const soulsDirectory = path.join(root, "souls");
const soulDirectories = (await readdir(soulsDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && !entry.name.startsWith("_"))
  .sort((a, b) => a.name.localeCompare(b.name));

if (soulDirectories.length === 0) {
  fail(soulsDirectory, "no public persona directories found");
}

const souls = await Promise.all(
  soulDirectories.map(async (directory) => {
    const file = path.join(soulsDirectory, directory.name, "README.md");
    const metadata = await readMetadata(file);
    requireExactKeys(file, metadata, ["mark", "name", "order", "state", "status", "voice"]);
    if (!Number.isInteger(metadata.order) || metadata.order < 1) {
      fail(file, '"order" must be a positive integer');
    }
    if (!states.has(metadata.state)) {
      fail(file, `"state" must be one of: ${[...states].join(", ")}`);
    }
    const mark = requireText(file, metadata.mark, "mark");
    if (!/^[A-Z]{2,3}$/.test(mark)) {
      fail(file, '"mark" must contain 2-3 uppercase letters');
    }
    return {
      order: metadata.order,
      name: requireText(file, metadata.name, "name"),
      mark,
      voice: requireText(file, metadata.voice, "voice"),
      status: requireText(file, metadata.status, "status"),
      state: metadata.state,
    };
  }),
);

const orders = souls.map(({ order }) => order);
if (new Set(orders).size !== orders.length) {
  fail(soulsDirectory, 'persona "order" values must be unique');
}

souls.sort((a, b) => a.order - b.order);
const publicSouls = souls.map(({ order: _order, ...soul }) => soul);

const source = `// Generated by scripts/generate-public-content.mjs. Do not edit.
export type MethodStage = Readonly<{
  n: string;
  title: string;
  body: string;
  tag: string;
}>;

export type PublicSoul = Readonly<{
  name: string;
  mark: string;
  voice: string;
  status: string;
  state: "active" | "authored" | "planned";
}>;

export const stages: readonly MethodStage[] = ${JSON.stringify(stages, null, 2)};

export const souls: readonly PublicSoul[] = ${JSON.stringify(publicSouls, null, 2)};
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");
console.log(`[public-content] generated ${path.relative(root, outputPath)} from ${souls.length + 1} approved Markdown files`);